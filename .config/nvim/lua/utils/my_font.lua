--
-- Characters: ─│╶╴╵╷╭╮╰╯├┼┤┬┴
-- ╭┬╮
-- ├┼┤
-- ╰┴╯
function M.render(text)
    local lines = {}

    for row = 1, 5 do
        local line = {}

        for char in text:gmatch(".") do
            local glyph = font[char:upper()]
            if glyph then
                table.insert(line, glyph[row])
            end
        end

        lines[row] = table.concat(line, " ")
    end

    return table.concat(lines, "\n")
end

return M
